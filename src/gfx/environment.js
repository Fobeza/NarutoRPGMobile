    for (let i = 0; i < 16; i++) {
      if (vertical) p(c, x + i, y, i % 2 ? '#c5c297' : '#b5b386', 0.5, 16);
      else p(c, x, y + i, i % 2 ? '#d2cda2' : '#bdb88b', 16, 0.5);
    }
    // Узкая тканевая окантовка обрамляет целый мат 32×16, а не каждую клетку.
